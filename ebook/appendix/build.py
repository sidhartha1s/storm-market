#!/usr/bin/env python3
"""Render Appendix B and the 50 state packets from state_data.csv.

Fails loudly. A published emergency directory with a guessed phone number is worse
than one with a blank cell, so every value-bearing field must carry a source URL and
every row must carry the date it was verified.
"""

import argparse
import base64
import csv
import html
import re
import subprocess
import sys
import zipfile
from io import BytesIO
from pathlib import Path

HERE = Path(__file__).parent
CSV_PATH = HERE / "state_data.csv"
TEMPLATES = HERE / "templates"
D = "—"          # em dash, used in generated titles
BOOK_CSS = HERE.parent / "build" / "book.css"
CHROME = r"C:/Program Files/Google/Chrome/Application/chrome.exe"

# The FREE edition's closing page. Buyers of the paid ebook bundle already own the book, so
# the default build (no --rehook) must never carry this page — only the $0 Gumroad packet
# product does.
REHOOK_URL = "https://paulraymond.online/packet?utm_source=packet&utm_medium=pdf&utm_campaign=qr"

# States per Appendix B page. fitcheck.mjs is the real gate on this number.
# Dropped from 4 to 3 on 2026-08-02: adding energy_assist_phone to the Appendix B row pushed
# Maine, Rhode Island and Texas past the safe area at 4/page (up to +25px). 3/page passes.
PER_PAGE = 3   # 17 pages, verified against fitcheck after adding energy_assist_phone
FRONT_MATTER = HERE.parent / "manuscript" / "P0-front-matter.md"
OUT = HERE / "out"

# Hazard names must match a Part Three playbook exactly, so the packet can say
# "see Playbook 7" and be right.
PLAYBOOKS = {
    "Tornado": 1,
    "Hurricane and storm surge": 2,
    "Extreme rainfall and flash flood": 3,
    "Riverine and coastal flooding": 4,
    "Wildfire": 5,
    "Wildfire smoke": 6,
    "Hail and derecho": 7,
    "Lightning": 8,
    "Blizzard and ice storm": 9,
    "Extreme heat": 10,
    "Extreme cold": 11,
    "Drought and dust": 12,
    "Earthquake": 13,
    "Tsunami": 14,
    "Space weather": 15,
    "Volcanic ashfall": 16,
}

REGIONS = {"Tornado Alley", "Hurricane Coast", "Wildfire West", "Ice & Snow North", "Quake West"}

# Every field here is only publishable alongside its *_src column.
SOURCED_FIELDS = [
    "em_url", "em_phone", "alerts_url", "doi_url", "doi_phone",
    "mitigation_url", "pharmacy_refill_law", "energy_assist_url", "energy_assist_phone",
    "well_test_url",
]

DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def load_rows():
    if not CSV_PATH.exists():
        sys.exit(f"FAIL: {CSV_PATH} does not exist.")
    with CSV_PATH.open(newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        sys.exit(
            "FAIL: state_data.csv has no rows.\n"
            "This is expected until the directory research is done — see README.md.\n"
            "No placeholder output is generated by design."
        )
    return rows


def validate(rows):
    """Return (complete_rows, problems). A row with any problem is never rendered."""
    problems = []
    complete = []
    seen = set()

    for i, row in enumerate(rows, start=2):  # +2: header is line 1
        state = (row.get("state") or "").strip() or f"<row {i}>"
        errs = []

        abbr = (row.get("abbr") or "").strip()
        if not re.fullmatch(r"[A-Z]{2}", abbr):
            errs.append(f"abbr {abbr!r} is not two uppercase letters")
        elif abbr in seen:
            errs.append(f"duplicate abbr {abbr}")
        else:
            seen.add(abbr)

        verified = (row.get("verified_on") or "").strip()
        if not DATE_RE.fullmatch(verified):
            errs.append("verified_on missing or not ISO yyyy-mm-dd")

        # A value without its source is not publishable. An empty pair is an honest gap.
        for field in SOURCED_FIELDS:
            value = (row.get(field) or "").strip()
            src = (row.get(field + "_src") or "").strip()
            if value and not src:
                errs.append(f"{field} has a value but {field}_src is empty")
            if src and not src.startswith("https://"):
                errs.append(f"{field}_src is not an https:// URL")

        for field in ("em_url", "alerts_url", "doi_url", "mitigation_url", "energy_assist_url", "well_test_url"):
            value = (row.get(field) or "").strip()
            if value and not value.startswith("https://"):
                errs.append(f"{field} is not an https:// URL")

        hazards = [(row.get(f"hazard_{n}") or "").strip() for n in (1, 2, 3)]
        if not hazards[0]:
            errs.append("hazard_1 is empty")
        for hazard in hazards:
            if hazard and hazard not in PLAYBOOKS:
                errs.append(f"hazard {hazard!r} does not match a Part Three playbook name")

        overlay = [r.strip() for r in (row.get("region_overlay") or "").split("|") if r.strip()]
        if not overlay:
            errs.append("region_overlay is empty")
        for region in overlay:
            if region not in REGIONS:
                errs.append(f"region_overlay {region!r} is not one of the five book regions")

        if errs:
            problems.append((state, errs))
        else:
            complete.append(row)

    return complete, problems


def report(rows, complete, problems):
    print(f"state_data.csv — {len(rows)} row(s), {len(complete)} complete, {len(problems)} with problems")
    for state, errs in problems:
        print(f"\n  {state}")
        for err in errs:
            print(f"    - {err}")
    missing = 51 - len(rows)
    if missing > 0:
        print(f"\n  {missing} state(s)/DC not yet in the file.")


def region_first_ten():
    """Parse the region priority table out of the book's own front matter.

    The packet cover promises "your first ten protections" and used to print only the hazards,
    so the promise went unmet. The list is not re-typed here: it is read from the same table
    the reader sees in the front matter, so the packet cannot drift from the book. If that
    table is edited, the packets follow on the next build; if it is moved or restructured, this
    fails loudly rather than shipping packets with a silently empty column.
    """
    if not FRONT_MATTER.exists():
        sys.exit(f"FAIL: {FRONT_MATTER} is missing — cannot build the first-ten lists.")
    lines = FRONT_MATTER.read_text(encoding="utf-8").splitlines()

    header = None
    for i, line in enumerate(lines):
        if line.startswith("|") and all(region in line for region in REGIONS):
            header = i
            break
    if header is None:
        sys.exit("FAIL: the region priority table was not found in the front matter. "
                 "If it moved, update region_first_ten().")

    columns = [cell.strip().strip("*") for cell in lines[header].strip().strip("|").split("|")]
    order = columns[1:]                      # first column is the rank number
    if set(order) != REGIONS:
        sys.exit(f"FAIL: the table's columns {order} are not the five book regions.")

    table = {region: [] for region in order}
    for line in lines[header + 2:]:          # +2 skips the markdown separator row
        if not line.startswith("|"):
            break
        cells = [cell.strip().strip("*") for cell in line.strip().strip("|").split("|")]
        if len(cells) != len(columns) or not cells[0].isdigit():
            break
        for region, value in zip(order, cells[1:]):
            table[region].append(value)

    for region, items in table.items():
        if len(items) != 10:
            sys.exit(f"FAIL: {region} has {len(items)} first-ten entries, expected 10.")
    return table


def first_ten_html(row, table):
    """Render one ranked column per region the state belongs to, side by side."""
    regions = [r.strip() for r in (row.get("region_overlay") or "").split("|") if r.strip()]
    if not regions:
        return ""
    columns = []
    for region in regions:
        items = "".join(
            f'<li>{html.escape(item)}</li>' for item in table.get(region, []))
        columns.append(f'<div class="pk-ten-col"><h4>{html.escape(region)}</h4>'
                       f'<ol class="pk-ten">{items}</ol></div>')
    intro = ("Do both, in this order \u2014 the overlap is larger than you expect."
             if len(regions) > 1 else "Do these first, in this order.")
    return (f'<p class="pk-ten-intro">{intro}</p>'
            f'<div class="pk-ten-wrap">{"".join(columns)}</div>')


def document(title, body):
    """Wrap rendered HTML in a self-contained page with the stylesheets inlined.

    Inlined rather than linked on purpose. A packet is handed to a buyer as a standalone PDF
    or HTML file, so a relative <link> to a path inside this repo breaks the moment the file
    moves — and it was already broken here: the template linked ../../build/book.css, which
    from out/packets/ resolved to a directory that does not exist, so every packet rendered
    with no styling at all.
    """
    css = []
    for path in (BOOK_CSS, TEMPLATES / "packet.css"):
        if not path.exists():
            sys.exit(f"FAIL: stylesheet {path} is missing.")
        css.append(f"/* {path.name} */\n{path.read_text(encoding='utf-8')}")
    return ("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
            f"<title>{html.escape(title)}</title>\n<style>\n" + "\n".join(css) +
            f"\n</style>\n</head>\n<body>\n{body}\n</body>\n</html>\n")


def read_template(name):
    path = TEMPLATES / name
    if not path.exists():
        sys.exit(f"FAIL: template {path} is missing.")
    return path.read_text(encoding="utf-8")


def fill(template, row, first_ten=""):
    """Substitute {{field}} placeholders. Unknown or empty fields render as an em dash,
    never as invented text."""
    def sub(match):
        key = match.group(1).strip()
        if key == "playbook_1":
            return str(PLAYBOOKS.get((row.get("hazard_1") or "").strip(), ""))
        if key == "playbook_2":
            return str(PLAYBOOKS.get((row.get("hazard_2") or "").strip(), ""))
        if key == "playbook_3":
            return str(PLAYBOOKS.get((row.get("hazard_3") or "").strip(), ""))
        if key == "first_ten":
            return first_ten
        if key == "regions":
            return ", ".join(r.strip() for r in (row.get("region_overlay") or "").split("|") if r.strip())
        value = (row.get(key) or "").strip()
        return html.escape(value) if value else "—"

    return re.sub(r"\{\{([a-z0-9_]+)\}\}", sub, template)


def build_appendix(complete, per_page=PER_PAGE):
    """Render Appendix B into fixed 6x9 pages, per_page states to a page.

    The pages do not reflow, so pagination is explicit rather than left to the browser, and
    fitcheck.mjs is the gate: if a page overflows, lower per_page or tighten the row. The first
    version put all 51 states on one page and overflowed it by 24,533px, and 4 per page only
    fits because the row was tightened afterwards — Texas and Washington, whose three hazard
    names are the longest in the set, were the states that decided it.
    """
    row_tpl = read_template("appendix_row.html")
    ordered = sorted(complete, key=lambda r: r["state"])
    pages = []
    for start in range(0, len(ordered), per_page):
        rows = "\n".join(fill(row_tpl, row) for row in ordered[start:start + per_page])
        folio = start // per_page + 1
        pages.append(
            f'<section class="page">\n'
            f'<p class="runhead">Appendix B {D} State Authority Directory</p>\n'
            f'{rows}\n<p class="folio">{folio}</p>\n</section>')
    OUT.mkdir(parents=True, exist_ok=True)
    target = OUT / "appendix-b.html"
    target.write_text(document(f"Appendix B {D} State Authority Directory", "\n".join(pages)),
                      encoding="utf-8")
    print(f"wrote {target} — {len(complete)} state row(s) on {len(pages)} page(s), "
          f"{per_page} per page")


def make_qr_data_uri(data):
    """PNG QR code, error-correction M, as a base64 data: URI so the packet stays a
    standalone file (no separate image asset to lose track of)."""
    try:
        import qrcode
    except ImportError:
        sys.exit("FAIL: the 'qrcode' package is required for --rehook. Install with "
                 "'pip install \"qrcode[pil]\"'.")
    img = qrcode.make(data, error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=10, border=2)
    buf = BytesIO()
    img.save(buf, format="PNG")
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode("ascii")


def build_packets(complete, only=None, rehook=False):
    tpl = read_template("packet.html")
    table = region_first_ten()
    directory = OUT / ("packets-free" if rehook else "packets")
    directory.mkdir(parents=True, exist_ok=True)

    rehook_html = ""
    if rehook:
        qr_uri = make_qr_data_uri(REHOOK_URL)
        rehook_html = read_template("rehook.html").replace("{{qr_data_uri}}", qr_uri)

    written = 0
    for row in complete:
        if only and row["abbr"] not in only:
            continue
        target = directory / f"{row['abbr']}.html"
        title = f"The Storm-Ready Home {D} {row['state']} State Packet"
        body = fill(tpl, row, first_ten=first_ten_html(row, table)) + rehook_html
        target.write_text(document(title, body), encoding="utf-8")
        written += 1
    print(f"wrote {written} packet(s) to {directory}" + (" (FREE edition, +rehook page)" if rehook else ""))
    if not written:
        sys.exit("FAIL: no packets written — no complete rows matched.")


def render_pdfs(directory):
    """Chrome headless print-to-pdf, one packet at a time. Chrome refuses a relative
    --print-to-pdf path with 'Access is denied', so every path here is resolved absolute
    (same constraint review_pdf.py works around)."""
    html_files = sorted(directory.glob("*.html"))
    if not html_files:
        sys.exit(f"FAIL: no .html files in {directory} — run --packets first.")
    for html_path in html_files:
        pdf_path = html_path.with_suffix(".pdf").resolve()
        subprocess.run(
            [CHROME, "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
             f"--print-to-pdf={pdf_path}", html_path.resolve().as_uri()],
            check=True, capture_output=True,
        )
    print(f"wrote {len(html_files)} PDF(s) in {directory}")


def build_zip(directory, zip_name):
    pdfs = sorted(directory.glob("*.pdf"))
    if not pdfs:
        sys.exit(f"FAIL: no .pdf files in {directory} — run --pdf first.")
    zip_path = OUT / zip_name
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for pdf in pdfs:
            zf.write(pdf, arcname=pdf.name)
    print(f"wrote {zip_path} — {len(pdfs)} PDF(s), {zip_path.stat().st_size / 1_048_576:.1f} MB")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate the CSV and exit")
    parser.add_argument("--appendix", action="store_true", help="render Appendix B")
    parser.add_argument("--per-page", type=int, default=PER_PAGE,
                        help=f"states per Appendix B page (default {PER_PAGE}); lower it if "
                             "fitcheck reports an overflow")
    parser.add_argument("--packets", action="store_true", help="render the per-state packets")
    parser.add_argument("--only", help="comma-separated state abbreviations")
    parser.add_argument("--rehook", action="store_true",
                        help="FREE edition only: add the buy-the-book QR page, and write to "
                             "out/packets-free/ instead of out/packets/. Never applies to the "
                             "paid bundle build — run --packets a second time WITHOUT --rehook "
                             "for that.")
    parser.add_argument("--pdf", action="store_true",
                        help="Chrome print-to-pdf every packet in the --rehook (or default) "
                             "output directory")
    parser.add_argument("--zip", action="store_true",
                        help="zip that directory's PDFs into out/The-Storm-Ready-Home-"
                             "State-Packets[-FREE].zip")
    args = parser.parse_args()

    if not (args.check or args.appendix or args.packets or args.pdf or args.zip):
        parser.error("nothing to do — pass --check, --appendix, --packets, --pdf or --zip")

    rows = load_rows()
    complete, problems = validate(rows)
    report(rows, complete, problems)

    if problems:
        # Rendering a partially-verified directory is how a wrong phone number ships.
        sys.exit(f"\nFAIL: {len(problems)} row(s) have problems. Fix them or empty the offending cells.")

    if args.check:
        print("\nOK")
        return

    only = {a.strip().upper() for a in args.only.split(",")} if args.only else None
    if args.appendix:
        build_appendix(complete, per_page=args.per_page)
    if args.packets:
        build_packets(complete, only, rehook=args.rehook)

    directory = OUT / ("packets-free" if args.rehook else "packets")
    if args.pdf:
        render_pdfs(directory)
    if args.zip:
        zip_name = ("The-Storm-Ready-Home-State-Packets-FREE.zip" if args.rehook
                   else "The-Storm-Ready-Home-State-Packets.zip")
        build_zip(directory, zip_name)


if __name__ == "__main__":
    main()
